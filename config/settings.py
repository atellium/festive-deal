def load_env_file(path):
    if not path.exists():
        return

    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith('#') or '=' not in line:
            continue

        key, value = line.split('=', 1)
        key = key.strip()
        value = value.strip().strip('"').strip("'")
        os.environ.setdefault(key, value)


def env_bool(name, default=False):
    value = os.environ.get(name)
    if value is None:
        return default
    return value.lower() in {'1', 'true', 'yes', 'on'}


def env_list(name, default=None):
    value = os.environ.get(name)
    if not value:
        return default or []
    return [item.strip() for item in value.split(',') if item.strip()]


def database_config_from_url(url):
    parsed = urlparse(url)

    if parsed.scheme == 'sqlite':
        name = unquote(parsed.path.lstrip('/')) or BASE_DIR / 'db.sqlite3'
        if name != ':memory:':
            name = BASE_DIR / name if not Path(name).is_absolute() else Path(name)
        return {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': name,
        }

    engines = {
        'postgres': 'django.db.backends.postgresql',
        'postgresql': 'django.db.backends.postgresql',
        'mysql': 'django.db.backends.mysql',
    }
    if parsed.scheme not in engines:
        raise ValueError(f'Unsupported DATABASE_URL scheme: {parsed.scheme}')

    config = {
        'ENGINE': engines[parsed.scheme],
        'NAME': unquote(parsed.path.lstrip('/')),
        'USER': unquote(parsed.username or ''),
        'PASSWORD': unquote(parsed.password or ''),
        'HOST': parsed.hostname or '',
        'PORT': str(parsed.port or ''),
    }

    options = parse_qs(parsed.query)
    if options:
        config['OPTIONS'] = {key: values[-1] for key, values in options.items()}

    return config


